function getLanguage() {
  const saved = window.localStorage.getItem(languageStorageKey);
  if (saved && translations[saved]) return saved;
  const detected = (navigator.language || "en").slice(0, 2).toLowerCase();
  return translations[detected] ? detected : "en";
}

function applyLanguage(language) {
  const copy = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.title = copy.pageTitle;
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", copy.pageDescription);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = copy[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  const selectedLanguage = languageMeta[language] || languageMeta.en;
  languageCurrentFlag.className = `language-flag flag-${language}`;
  languageCurrentName.textContent = selectedLanguage.name;
  languageOptions.forEach((option) => {
    option.setAttribute("aria-selected", String(option.dataset.language === language));
  });
  window.localStorage.setItem(languageStorageKey, language);
  applyReleaseUi(copy);
}

function applyReleaseUi(copy) {
  const heroPrimary = document.getElementById("hero-primary");
  const primary = document.getElementById("download-primary");
  const downloadCopy = document.getElementById("download-copy");
  const heroNote = document.getElementById("hero-note");
  if (!primary || !downloadCopy || !heroNote) return;
  if (latestRelease) {
    if (heroPrimary) {
      heroPrimary.href = latestRelease.downloadUrl;
      heroPrimary.textContent = copy.downloadRelease;
    }
    primary.href = latestRelease.downloadUrl;
    primary.textContent = copy.downloadRelease;
    downloadCopy.textContent = copy.downloadReleaseCopy;
    heroNote.textContent = copy.heroReleaseNote.replace("{0}", latestRelease.version);
    return;
  }
  if (heroPrimary) {
    heroPrimary.href = "#download";
    heroPrimary.textContent = copy.ctaBuild;
  }
  primary.href = releaseRepositoryUrl;
  primary.textContent = copy.openGithub;
  downloadCopy.textContent = copy.downloadCopy;
  heroNote.textContent = copy.heroNote;
}

async function loadLatestRelease() {
  try {
    const response = await fetch(releaseApiUrl, {
      headers: { Accept: "application/vnd.github+json" },
      signal: AbortSignal.timeout(5000)
    });
    if (!response.ok) return;
    const releases = await response.json();
    const release = Array.isArray(releases) ? releases.find((item) => !item.draft && !item.prerelease) : null;
    if (!release) return;
    if (!release.html_url || !release.tag_name) return;
    const asset = Array.isArray(release.assets)
      ? release.assets.find((item) => /\.(zip|exe)$/i.test(item.name) && item.browser_download_url)
      : null;
    latestRelease = {
      version: release.tag_name,
      downloadUrl: asset?.browser_download_url || release.html_url
    };
    applyReleaseUi(translations[getLanguage()] || translations.en);
  } catch {
  }
}

